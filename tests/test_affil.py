def test_clean_numbered_block():
    affs = parse_affiliations(CLEAN_NUMBERED)
    assert affs == ["Harvard University, Cambridge",
                    "Massachusetts Institute of Technology, Cambridge",
                    "Google Quantum AI, Santa Barbara"]


def test_footnote_style_drops_markups_emails_and_equal_contribution():
    affs = parse_affiliations(FOOTNOTE_STYLE)
    assert affs == ["Harvard University, Cambridge",
                    "University of California, Berkeley",
                    "Google Quantum AI, Santa Barbara",
                    "Lawrence Berkeley National Laboratory, Berkeley"]
    assert not any("contributed" in a for a in affs)
    assert not any("@" in a for a in affs)


def test_group_author_paper_still_yields_institutions():
    affs = parse_affiliations(GROUP_AUTHOR)
    assert affs == ["QuEra Computing, Boston",
                    "Harvard University, Cambridge",
                    "Cavendish Laboratory, University of Cambridge, Cambridge"]


def test_garbage_fails_open_to_empty():
    assert parse_affiliations(GARBAGE) == []


def test_prl_style_no_abstract_heading_and_wrapped_affiliations():
    # the boundary falls back to the first long plain line; a trailing comma
    # merges the wrapped continuation; identical affiliations dedupe
    affs = parse_affiliations(PRL_STYLE)
    assert affs == ["Harvard University, Cambridge",
                    "Harvard-MIT Center for Ultracold Atoms, Cambridge"]
    assert not any("Ultracold" in a and "Center" not in a for a in affs)


def test_dutch_zip_and_trailing_and_separator():
    # verbatim structure of the real arXiv:2610.26413 block: zip-first address
    # segments, a country tail, and a multi-affiliation "and" separator
    text = """Two-qubit cryo-CMOS control of a spin register in diamond
H. B. van Ommen 1,2 N. E. Fakkel 1,3 M. van Riggelen 1,2
1QuTech, Delft University of Technology, 2628 CJ Delft, The Netherlands
2Kavli Institute of Nanoscience Delft, Delft University of Technology, 2628 CJ Delft, The Netherlands
3Department of Quantum and Computer Engineering, Delft University of Technology, 2628 CD Delft, The Netherlands and
4Department of Microelectronics, Delft University of Technology, 2628 CD Delft, The Netherlands
Utility-scale quantum technologies will not only require a well-performing quantum platform, but also
classical control hardware that is scalable, efficient, and meets the design requirements set by the quantum
"""
    affs = parse_affiliations(text)
    assert affs == ["QuTech, Delft University of Technology",
                    "Kavli Institute of Nanoscience Delft, Delft University of Technology",
                    "Delft University of Technology"]
    assert not any("2628" in a or "Netherlands" in a or "and" in a.lower() for a in affs)


def test_dedupe_preserves_first_seen_order():
    text = CLEAN_NUMBERED.replace(
        "3 Google Quantum AI, Santa Barbara, CA",
        "3 Google Quantum AI, Santa Barbara, CA\n4 Google Quantum AI, Santa Barbara, CA",
    )
    assert parse_affiliations(text).count("Google Quantum AI, Santa Barbara") == 1
